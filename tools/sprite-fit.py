#!/usr/bin/env python3
"""Regenerate js/sprite-fit.js. Run after adding/changing character art:  python3 tools/sprite-fit.py
WWYF_SPRITE_DX[id]  = horizontal shift (fraction of image width, + = right) that puts the
                      head-weighted visual centre (stale1 alpha) on the circle centre — small cards.
WWYF_SPRITE_BOX[id] = [left, top, right, bottom] alpha bbox (fractions of the image box,
                      mean of the stale1 + stale2 boxes, ears/tail/feet included) — big pick circle
                      centres this box exactly."""
import glob, json, os
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = {}
box = {}
for f in sorted(glob.glob(os.path.join(ROOT, 'assets/characters/*/stale1.webp'))):
    a = np.array(Image.open(f).convert('RGBA'))[:, :, 3] > 20
    ys, xs = np.nonzero(a)
    if not len(xs):
        continue
    w = a.shape[1]
    top, bot = ys.min(), ys.max()
    head = a[top:top + int((bot - top) * 0.45)]
    hy, hx = np.nonzero(head)
    head_cx = (hx.min() + hx.max()) / 2 / w          # centre of the head/ears band
    mass_cx = xs.mean() / w                           # centre of all opaque pixels
    cx = 0.7 * head_cx + 0.3 * mass_cx                # the head is what reads as "the middle"
    dx = round(0.5 - cx, 3)
    h = a.shape[0]
    bb = [xs.min() / w, ys.min() / h, (xs.max() + 1) / w, (ys.max() + 1) / h]
    f2 = f.replace('stale1', 'stale2')
    if os.path.exists(f2):
        a2 = np.array(Image.open(f2).convert('RGBA'))[:, :, 3] > 20
        y2, x2 = np.nonzero(a2)
        if len(x2):
            b2 = [x2.min() / w, y2.min() / h, (x2.max() + 1) / w, (y2.max() + 1) / h]
            bb = [(p + q) / 2 for p, q in zip(bb, b2)]   # mean of the two idle frames -> each frame within ~1-2px of centre
    box[os.path.basename(os.path.dirname(f))] = [round(v, 3) for v in bb]
    if abs(dx) >= 0.005:
        out[os.path.basename(os.path.dirname(f))] = dx

js = ('/* generated by tools/sprite-fit.py — do not edit by hand */\n'
      'window.WWYF_SPRITE_DX = ' + json.dumps(out, separators=(',', ':')) + ';\n'
      'window.WWYF_SPRITE_BOX = ' + json.dumps(box, separators=(',', ':')) + ';\n'
      'window.wwyfSpriteDx = function (id) { return (window.WWYF_SPRITE_DX[id] || 0); };\n'
      'window.wwyfSpriteBox = function (id) { return window.WWYF_SPRITE_BOX[id] || [0.1, 0.15, 0.9, 0.96]; };\n')
open(os.path.join(ROOT, 'js/sprite-fit.js'), 'w').write(js)
print(js)
