#!/usr/bin/env python3
"""Regenerate js/sprite-fit.js — per-character horizontal offsets so each sprite's
*visual* centre (head-weighted, from the stale1 alpha channel) sits on the centre of
its circle. Run after adding/changing character art:  python3 tools/sprite-fit.py
dx = fraction of the image width to shift the sprite (positive = right)."""
import glob, json, os
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = {}
for f in sorted(glob.glob(os.path.join(ROOT, 'assets/characters/*/stale1.webp'))):
    a = np.array(Image.open(f).convert('RGBA'))[:, :, 3] > 20
    ys, xs = np.nonzero(a)
    if not len(xs):
        continue
    w = a.shape[1]
    top, bot = ys.min(), ys.max()
    head = a[top:top + int((bot - top) * 0.45)]
    hy, hx = np.nonzero(head)
    head_cx = (hx.min() + hx.max()) / 2 / w          # centre of the head/ears band
    mass_cx = xs.mean() / w                           # centre of all opaque pixels
    cx = 0.7 * head_cx + 0.3 * mass_cx                # the head is what reads as "the middle"
    dx = round(0.5 - cx, 3)
    if abs(dx) >= 0.005:
        out[os.path.basename(os.path.dirname(f))] = dx

js = ('/* generated by tools/sprite-fit.py — do not edit by hand */\n'
      'window.WWYF_SPRITE_DX = ' + json.dumps(out, separators=(',', ':')) + ';\n'
      'window.wwyfSpriteDx = function (id) { return (window.WWYF_SPRITE_DX[id] || 0); };\n')
open(os.path.join(ROOT, 'js/sprite-fit.js'), 'w').write(js)
print(js)
